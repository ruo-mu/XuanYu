#!/usr/bin/env python3
"""Generate thin invoke wrappers from dispatch_gen.inc → desktopIpc.gen.ts.

Signatures prefer positional args (matching existing desktopIpc.ts call sites).
Single `payload` field unwraps so callers pass the payload value directly.
"""

from __future__ import annotations

import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DISPATCH = ROOT / "crates/xuanyu-desktop-host/src/dispatch_gen.inc"
OUT = ROOT / "apps/desktop-ui/src/ipc/desktopIpc.gen.ts"

SKIP = {
    "init_postgres_install",
    "permission_respond",
    "event_replay_filtered",
    "app_updater_install",
    "app_updater_relaunch",
    "launch_setup_app",
}


def snake_to_camel(name: str) -> str:
    parts = name.split("_")
    return parts[0] + "".join(p.title() for p in parts[1:])


def parse_helpers(text: str) -> list[tuple[str, list[tuple[str, bool]]]]:
    results: list[tuple[str, list[tuple[str, bool]]]] = []
    for match in re.finditer(
        r"async fn dispatch_([a-z0-9_]+)\((.*?)\)\s*->\s*Result<Value, String>\s*\{([\s\S]*?)\n\}",
        text,
    ):
        cmd = match.group(1)
        params_sig = match.group(2)
        body = match.group(3)
        if cmd in SKIP:
            continue
        fields: list[tuple[str, bool]] = []
        if "params: Value" in params_sig:
            struct = re.search(r"struct Params\s*\{([\s\S]*?)\}", body)
            if struct:
                pending_optional = False
                for line in struct.group(1).splitlines():
                    raw = line.strip().rstrip(",")
                    if not raw:
                        continue
                    if raw.startswith("#[serde(default)]") or raw.startswith("#[serde(default,"):
                        pending_optional = True
                        continue
                    if raw.startswith("#") or raw.startswith("//"):
                        continue
                    m = re.match(r"([a-zA-Z0-9_]+)\s*:\s*(.+)$", raw)
                    if not m:
                        continue
                    name, ty = m.group(1), m.group(2).strip()
                    optional = pending_optional or ty.startswith("Option<")
                    pending_optional = False
                    fields.append((name, optional))
        results.append((cmd, fields))
    return results


def emit(cmd: str, fields: list[tuple[str, bool]]) -> str:
    fn = snake_to_camel(cmd)
    if not fields:
        return (
            f"export async function {fn}<T = any>(): Promise<T> {{\n"
            f"  return invoke<T>({cmd!r});\n"
            f"}}\n"
        )

    if len(fields) == 1 and fields[0][0] == "payload":
        return (
            f"export async function {fn}<T = any>(payload: any): Promise<T> {{\n"
            f"  return invoke<T>({cmd!r}, {{ payload }});\n"
            f"}}\n"
        )

    # Keep required before optional for valid TS positional params
    ordered = sorted(fields, key=lambda item: (item[1], fields.index(item)))
    args: list[str] = []
    assign_entries: list[str] = []
    for snake, optional in ordered:
        camel = snake_to_camel(snake)
        if optional:
            args.append(f"{camel}?: any")
        else:
            args.append(f"{camel}: any")
        assign_entries.append(f"    {camel},")
    arg_list = ", ".join(args)
    return (
        f"export async function {fn}<T = any>({arg_list}): Promise<T> {{\n"
        f"  return invoke<T>({cmd!r}, {{\n"
        + "\n".join(assign_entries)
        + "\n  });\n"
        f"}}\n"
    )


def main() -> None:
    text = DISPATCH.read_text(encoding="utf-8")
    helpers = parse_helpers(text)
    parts = [
        "/* AUTO-GENERATED by scripts/gen-desktop-ipc-wrappers.py — do not edit */",
        "import { invoke } from './desktopIpcInvoke';",
        "",
    ]
    for cmd, fields in helpers:
        parts.append(emit(cmd, fields))
        parts.append("")
    OUT.write_text("\n".join(parts), encoding="utf-8")
    print(f"wrote {OUT} wrappers={len(helpers)}")


if __name__ == "__main__":
    main()
